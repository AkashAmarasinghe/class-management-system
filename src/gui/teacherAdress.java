     private void loadAddress(String email){
    
        try {
            
          
            ResultSet resultSet = mySql.executeSearch("SELECT * FROM `teacher_address` WHERE `teacher_email` = '"+email+"'");
            
            DefaultTableModel model = (DefaultTableModel)jTable1.getModel();
            model.setRowCount(0);
            
            while (resultSet.next()) {                
                Vector vector = new Vector();
                vector.add(resultSet.getString("line1"));                
                vector.add(resultSet.getString("line2"));
                vector.add(resultSet.getString("mobile2"));
                vector.add(resultSet.getString("teacher_email"));

                            model.addRow(vector);

            }
            
        } catch (Exception e) {
            e.printStackTrace();
        }
    }


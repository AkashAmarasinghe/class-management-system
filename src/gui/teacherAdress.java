    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String line1 = jTextField1.getText();
        String line2 = jTextField2.getText();
        String mobile = jTextField3.getText();
        String email = jLabel3.getText();

        if (line1.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Your Address Line1" , "Warning" , JOptionPane.ERROR_MESSAGE);
        } else if (line2.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please Enter Your Address Line2" , "Warning" , JOptionPane.ERROR_MESSAGE);
        } else if(mobile.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please Enter Another Mobiel Number" , "Warning" , JOptionPane.ERROR_MESSAGE);
        } else {

            try {

                ResultSet resultSet = mySql.executeSearch("SELECT * FROM `teacher_address` WHERE `teacher_email` = '"+email+"'");

                if (resultSet.next()) {
                    JOptionPane.showMessageDialog(this, "Allready email address Deatils registerd" , "Warning" , JOptionPane.ERROR_MESSAGE);

                } else {

                    mySql.executeIUD("INSERT INTO `teacher_address`"
                        + "(`line1`,`line2`,`mobile2`,`teacher_email`) VALUES ('"+line1+"', '"+line2+"' , '"+mobile+"' , '"+email+"')");

                    loadAddress(email);
                    reset();
                }
            } catch (Exception e) {
                e.printStackTrace();

            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        String line1 = jTextField1.getText();
        String line2 = jTextField2.getText();
        String mobile = jTextField3.getText();
        String email = jLabel3.getText();

        if (line1.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Your Address Line1" , "Warning" , JOptionPane.ERROR_MESSAGE);
        } else if (line2.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please Enter Your Address Line2" , "Warning" , JOptionPane.ERROR_MESSAGE);
        } else if(mobile.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please Enter Another Mobiel Number" , "Warning" , JOptionPane.ERROR_MESSAGE);
        } else {

            try {

                mySql.executeIUD("UPDATE `teacher_address` SET `line1` = '"+line1+"' , `line2` = '"+line2+"' , `mobile2` = '"+mobile+"' WHERE `teacher_email` = '"+email+"'");

                loadAddress(email);
                reset();

            } catch (Exception e) {
                e.printStackTrace();

            }
        }

    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed

        try {
            int selectedRow = jTable1.getSelectedRow();

            if (selectedRow == -1) {
                JOptionPane.showMessageDialog(this, "Please Select a row to Delete or Update" , "Warning" , JOptionPane.ERROR_MESSAGE);

            } else {

                String email = jLabel3.getText();

                mySql.executeIUD("DELETE FROM `teacher_address` WHERE `teacher_email` = '"+email+"' ");

                loadAddress(email);
                reset();
            }
        } catch (Exception e) {

            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton3ActionPerformed


    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        try {
            String uname = jTextField1.getText();
            String password = String.valueOf(jPasswordField1.getPassword());

            if (uname.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please Eneter Your User Name", "Warning", JOptionPane.ERROR_MESSAGE);
            } else if (password.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please Enter Your Password", "Warning", JOptionPane.ERROR_MESSAGE);
            } else {

                ResultSet resultSet = mySql.executeSearch("SELECT * FROM `admin` WHERE `uname` = '" + uname + "' AND `password`= '" + password + "'");

                if (resultSet.next()) {
                    this.dispose();

                    home dashboard = new home();
                    dashboard.setVisible(true);
                } else {
                    JOptionPane.showMessageDialog(this, " Invalid Password or Usernme, Try again", "Warning", JOptionPane.ERROR_MESSAGE);
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

